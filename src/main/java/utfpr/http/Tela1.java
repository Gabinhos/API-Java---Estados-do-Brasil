    public void carregarLista(int id){ // Função para pegar o ID do munipio selecionado e carregar na lista
        JsonToObjetos carregar = new JsonToObjetos();
        municipios_estado = carregar.buscarMunicipio(id);
        for(int i = 0; i<municipios_estado.size(); i++){
            Municipio temp = municipios_estado.get(i);
            modeloListaMunicipios.addElement(temp);
        }
    }
