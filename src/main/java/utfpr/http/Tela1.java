    private void istMunicipiosMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_istMunicipiosMouseClicked
        if(evt.getClickCount() == 2){//Se o usuario der 2 cliques na lista
        Municipio atual = (Municipio) modeloListaMunicipios.getElementAt(istMunicipios.getSelectedIndex());//Verifica qual foi o municipio clicado
        //E retorna o index do municipio
        
        DetalheMunicipio janelaMunicipio = new DetalheMunicipio(this, false); //"disponibiliza" a segunda tela. Deixei como não modal porque se quiser acessar dois
        //Municipios de uma vez tudo bem
        janelaMunicipio.setLocationRelativeTo(this);//Para a janela aparecer "em cima" da tela principal, pensei que somente com o "this" seria suficiente mas não estava indo
        String nome_atual = atual.getNome();//Passa o nome do municipio para uma variavel
        String id_atual = String.valueOf(atual.getId());//Passa o id do munipio para uma variavel, depois de fazer o value of para string
        String Uf_atual = atual.getSigla();//Passa a sigla(UF) para uma variavel
        String regiao_atual = atual.getRegiao();//Passa a região para uma variavel
        
        janelaMunicipio.setTxtNome(nome_atual);//Preencher com seus respectivos 
        janelaMunicipio.setTxtID(id_atual);
        janelaMunicipio.setTxtRegiao(regiao_atual);
        janelaMunicipio.setTxtUF(Uf_atual);
        
        
        janelaMunicipio.setVisible(true);
        }
    }//GEN-LAST:event_istMunicipiosMouseClicked

